const TONES = ["", "🏻", "🏼", "🏽", "🏾", "🏿"] as const;

function tones(emoji: string) {
  return TONES.map((tone) => {
    if (!tone) return emoji;
    const chars = [...emoji];
    if (chars.at(-1) === "\uFE0F") {
      chars.splice(chars.length - 1, 0, tone);
      return chars.join("");
    }
    return `${emoji}${tone}`;
  });
}

